const slideEl = document.querySelector("#slide");
const counterEl = document.querySelector("#counter");
const progressBarEl = document.querySelector("#progress-bar");
const announcerEl = document.querySelector("#announcer");
const prevButton = document.querySelector("#prev");
const nextButton = document.querySelector("#next");
const toggleIndexButton = document.querySelector("#toggle-index");
const closeIndexButton = document.querySelector("#close-index");
const indexPanel = document.querySelector("#index-panel");
const indexList = document.querySelector("#index-list");
const scrim = document.querySelector("#scrim");

let currentIndex = 0;
let revealedQuestions = 0;
let touchStartX = 0;
let touchStartY = 0;

function slideTitle(slide) {
  if (slide.type === "cover") return slide.title;
  if (slide.type === "section") return slide.section;
  if (slide.type === "closing") return slide.title;
  return slide.section;
}

function quoteSize(quote) {
  const length = quote.length;
  if (length > 135) return "clamp(1.35rem, 4.2vmin, 3.2rem)";
  if (length > 105) return "clamp(1.55rem, 4.8vmin, 3.6rem)";
  if (length > 80) return "clamp(1.8rem, 5.6vmin, 4.1rem)";
  return "";
}

function referenceText(slide) {
  return `Schultz, 1996, ${String(slide.page).includes("–") ? "pp." : "p."} ${slide.page}`;
}

function renderSlide() {
  const slide = deckData[currentIndex];
  slideEl.classList.add("is-leaving");

  window.setTimeout(() => {
    slideEl.innerHTML = "";
    slideEl.removeAttribute("style");

    if (slide.type === "cover") renderCover(slide);
    else if (slide.type === "section") renderSection(slide);
    else if (slide.type === "question") renderQuestionSlide(slide);
    else if (slide.type === "closing") renderClosing(slide);
    else renderQuote(slide);

    updateChrome();
    slideEl.classList.remove("is-leaving");
  }, 130);
}

function renderCover(slide) {
  slideEl.insertAdjacentHTML("beforeend", `
    <p class="kicker">Lectura en clase</p>
    <h1 id="slide-title" class="title">${slide.title}</h1>
    <p class="subtitle">${slide.subtitle}</p>
    <p class="reference">${slide.meta}</p>
  `);
}

function renderSection(slide) {
  slideEl.insertAdjacentHTML("beforeend", `
    <p class="kicker">Sección</p>
    <h1 id="slide-title" class="section-title">${slide.section}</h1>
  `);
}

function renderQuestionSlide(slide) {
  slideEl.insertAdjacentHTML("beforeend", `
    <p class="kicker">${slide.section}</p>
    <h1 id="slide-title" class="question-only">${slide.text}</h1>
  `);
}

function renderClosing(slide) {
  slideEl.insertAdjacentHTML("beforeend", `
    <h1 id="slide-title" class="section-title">${slide.title}</h1>
    <ul class="questions"><li>${slide.questions[0]}</li></ul>
  `);
}

function renderQuote(slide) {
  const size = quoteSize(slide.quote);
  if (size) slideEl.style.setProperty("--quote-size", size);

  slideEl.insertAdjacentHTML("beforeend", `
    <p class="kicker">${slide.section}</p>
    <h1 id="slide-title" class="quote">“${slide.quote}”</h1>
    ${slide.context ? `<p class="context-note">${slide.context}</p>` : ""}
    <p class="reference">${referenceText(slide)}</p>
    <div class="question-area">
      <button id="question-toggle" class="question-button" type="button" aria-expanded="${revealedQuestions > 0}" aria-controls="questions-list">
        ${revealedQuestions > 0 ? "Ocultar preguntas" : "Mostrar preguntas"}
      </button>
      <ul id="questions-list" class="questions" aria-live="polite">
        ${slide.questions.map((question, index) => `<li ${index >= revealedQuestions ? "hidden" : ""}>${question}</li>`).join("")}
      </ul>
    </div>
  `);

  document.querySelector("#question-toggle").addEventListener("click", toggleQuestions);
}

function toggleQuestions() {
  const slide = deckData[currentIndex];
  if (!slide.questions) return;
  if (revealedQuestions >= slide.questions.length) {
    revealedQuestions = 0;
  } else {
    revealedQuestions += 1;
  }
  renderSlide();
}

function updateChrome() {
  counterEl.textContent = `${String(currentIndex + 1).padStart(2, "0")} / ${String(deckData.length).padStart(2, "0")}`;
  progressBarEl.style.width = `${((currentIndex + 1) / deckData.length) * 100}%`;
  prevButton.disabled = currentIndex === 0;
  nextButton.disabled = currentIndex === deckData.length - 1;
  announcerEl.textContent = `Slide ${currentIndex + 1} de ${deckData.length}: ${slideTitle(deckData[currentIndex])}`;
  updateIndexCurrent();
}

function goTo(index) {
  const nextIndex = Math.max(0, Math.min(deckData.length - 1, index));
  if (nextIndex === currentIndex) return;
  currentIndex = nextIndex;
  revealedQuestions = 0;
  renderSlide();
}

function nextSlide() {
  goTo(currentIndex + 1);
}

function previousSlide() {
  goTo(currentIndex - 1);
}

function buildIndex() {
  const sectionIndexes = deckData
    .map((slide, index) => ({ slide, index }))
    .filter(({ slide }) => slide.type === "cover" || slide.type === "section" || slide.type === "closing");

  indexList.innerHTML = sectionIndexes.map(({ slide, index }) => `
    <button class="index-link" type="button" data-index="${index}">
      ${String(index + 1).padStart(2, "0")} · ${slideTitle(slide)}
    </button>
  `).join("");

  indexList.addEventListener("click", (event) => {
    const button = event.target.closest("[data-index]");
    if (!button) return;
    closeIndex();
    goTo(Number(button.dataset.index));
  });
}

function updateIndexCurrent() {
  const activeSectionIndex = findActiveSectionIndex();
  document.querySelectorAll(".index-link").forEach((button) => {
    button.setAttribute("aria-current", Number(button.dataset.index) === activeSectionIndex ? "true" : "false");
  });
}

function findActiveSectionIndex() {
  const slide = deckData[currentIndex];
  if (slide.type === "cover" || slide.type === "section" || slide.type === "closing") return currentIndex;
  for (let index = currentIndex; index >= 0; index -= 1) {
    if (deckData[index].type === "section") return index;
  }
  return 0;
}

function openIndex() {
  indexPanel.classList.add("is-open");
  indexPanel.setAttribute("aria-hidden", "false");
  scrim.hidden = false;
  closeIndexButton.focus();
}

function closeIndex() {
  indexPanel.classList.remove("is-open");
  indexPanel.setAttribute("aria-hidden", "true");
  scrim.hidden = true;
  toggleIndexButton.focus();
}

function toggleFullscreen() {
  if (!document.fullscreenElement) {
    document.documentElement.requestFullscreen?.();
  } else {
    document.exitFullscreen?.();
  }
}

prevButton.addEventListener("click", previousSlide);
nextButton.addEventListener("click", nextSlide);
toggleIndexButton.addEventListener("click", openIndex);
closeIndexButton.addEventListener("click", closeIndex);
scrim.addEventListener("click", closeIndex);

document.addEventListener("keydown", (event) => {
  if (event.key === "ArrowRight" || event.key === " ") {
    event.preventDefault();
    nextSlide();
  }
  if (event.key === "ArrowLeft") previousSlide();
  if (event.key === "Home") goTo(0);
  if (event.key === "End") goTo(deckData.length - 1);
  if (event.key.toLowerCase() === "f") toggleFullscreen();
  if (event.key === "Escape" && indexPanel.classList.contains("is-open")) closeIndex();
});

document.addEventListener("click", (event) => {
  if (event.target.closest("button, a, .index-panel")) return;
  if (event.clientX > window.innerWidth / 2) nextSlide();
  else previousSlide();
});

document.addEventListener("touchstart", (event) => {
  touchStartX = event.changedTouches[0].clientX;
  touchStartY = event.changedTouches[0].clientY;
}, { passive: true });

document.addEventListener("touchend", (event) => {
  const touch = event.changedTouches[0];
  const deltaX = touch.clientX - touchStartX;
  const deltaY = touch.clientY - touchStartY;
  if (Math.abs(deltaX) < 45 || Math.abs(deltaX) < Math.abs(deltaY)) return;
  if (deltaX < 0) nextSlide();
  else previousSlide();
}, { passive: true });

buildIndex();
renderSlide();
